function buildJsonLdGraph(sot, siteOrigin, brandSeo) {
  const orgId = siteOrigin + '/#organization';
  const websiteId = siteOrigin + '/#website';
  const personId = siteOrigin + '/#tomas';
  const social = sot.brand.socialProfiles || {};
  const sameAs = [
    siteOrigin + '/en/',
    'https://promptanatomy.app/',
    social.telegram,
    social.linkedin,
    social.x
  ].filter(Boolean);

  const faqEntities = (sot.frontFaq || []).concat(sot.buyerFaq || []).map(function (item) {
    return {
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: { '@type': 'Answer', text: item.a }
    };
  });

  const products = (sot.commerce && sot.commerce.products) || [];
  const productNodes = products.map(function (p) {
    const offer = {
      '@type': 'Offer',
      priceCurrency: 'USD',
      price: Number(p.priceUsd).toFixed(2),
      priceValidUntil: sot.geo && sot.geo.priceValidUntil ? sot.geo.priceValidUntil : '2027-12-31',
      availability: 'https://schema.org/InStock',
      url: siteOrigin + '/en/#pdf-storefront',
      hasMerchantReturnPolicy: {
        '@type': 'MerchantReturnPolicy',
        applicableCountry: 'US',
        returnPolicyCategory: 'https://schema.org/MerchantReturnFiniteReturnWindow',
        merchantReturnDays: 14,
        returnMethod: 'https://schema.org/ReturnByMail',
        returnFees: 'https://schema.org/FreeReturn'
      }
    };
    return {
      '@type': 'Product',
      '@id': siteOrigin + '/#product-' + p.id,
      name: p.name,
      description: p.subtitle,
      sku: 'cmo-' + p.id,
      brand: { '@type': 'Brand', name: sot.brand.publicName },
      offers: offer
    };
  });

  const graph = [
    {
      '@type': 'WebSite',
      '@id': websiteId,
      url: siteOrigin + '/',
      name: brandSeo.title,
      description: brandSeo.description,
      inLanguage: ['en', 'lt'],
      publisher: { '@id': orgId }
    },
    {
      '@type': 'Organization',
      '@id': orgId,
      name: sot.brand.publicName,
      url: siteOrigin + '/',
      logo: sot.brand.logoUrl,
      slogan: sot.brand.slogan,
      email: 'info@promptanatomy.app',
      knowsAbout: sot.brand.knowsAbout || [],
      sameAs: sameAs,
      founder: { '@id': personId }
    },
    {
      '@type': 'Person',
      '@id': personId,
      name: 'Tomas Staniulis',
      worksFor: { '@id': orgId },
      sameAs: [sot.brand.operatorLinkedin, sot.brand.operatorTwitter].filter(Boolean)
    },
    {
      '@type': 'FAQPage',
      '@id': siteOrigin + '/en/#faq',
      mainEntity: faqEntities
    }
  ].concat(productNodes);

  return JSON.stringify({ '@context': 'https://schema.org', '@graph': graph });
}

function injectEnJsonLdGraph(html, sot, siteOrigin, brandSeo) {
  const graphJson = buildJsonLdGraph(sot, siteOrigin, brandSeo);
  const scriptBlock =
    '    <script type="application/ld+json">\n        ' +
    graphJson +
    '\n    </script>';
  let out = html.replace(
    /\s*<script type="application\/ld\+json">[\s\S]*?<\/script>\s*<script type="application\/ld\+json">[\s\S]*?<\/script>/,
    '\n' + scriptBlock
  );
  out = out.replace(/\s*<script type="application\/ld\+json">\s*\{"@context":"https:\/\/schema\.org","@type":"FAQPage"[\s\S]*?<\/script>/, '');
  return out;
}

function writeGeoSurfaces(options) {
  const root = options.root;
  const siteOrigin = options.siteOrigin.replace(/\/$/, '');
  const sot = options.sot;
  const promptBodies = options.promptBodies || [];

  validateGeoFields(sot, siteOrigin);
  const brandSeo = readBrandSeo();
  const tokens = readDesignTokens();

  fs.writeFileSync(path.join(root, 'robots.txt'), buildRobotsTxt(siteOrigin), 'utf8');
  fs.writeFileSync(path.join(root, 'sitemap.xml'), buildSitemapXml(siteOrigin, root), 'utf8');
  fs.writeFileSync(path.join(root, 'llms.txt'), buildLlmsTxt(siteOrigin, brandSeo), 'utf8');
  fs.writeFileSync(path.join(root, 'llms-full.txt'), buildLlmsFullTxt(siteOrigin, promptBodies), 'utf8');
  fs.writeFileSync(path.join(root, INDEXNOW_KEY + '.txt'), INDEXNOW_KEY + '\n', 'utf8');
  fs.writeFileSync(path.join(root, '404.html'), build404Html(siteOrigin), 'utf8');
  fs.writeFileSync(path.join(root, 'manifest.webmanifest'), buildManifest(siteOrigin, tokens), 'utf8');
  fs.writeFileSync(path.join(root, 'site.webmanifest'), buildManifest(siteOrigin, tokens), 'utf8');

  return { INDEXNOW_KEY, injectEnJsonLdGraph: function (html) {
    return injectEnJsonLdGraph(html, sot, siteOrigin, brandSeo);
  }};
}


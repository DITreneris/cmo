function buildLlmsFullTxt(siteOrigin, promptBodies) {
  const lines = [
    '# CMO AI Content System — full prompt digest (Pro / offline kits)',
    '',
    'Cycle: Plan → Create → Check → Improve',
    '',
    'Free /en/: creative brief builder + 4 core interactive prompts (1, 2, 3, 5).',
    'Full 10 META/INPUT/OUTPUT bodies: Pro kit.',
    '',
    '## 10 prompts (system digest)',
    ''
  ];
  if (Array.isArray(promptBodies)) {
    promptBodies.forEach(function (body, i) {
      const firstLine = String(body).split('\n').find(function (l) { return l.trim(); }) || 'Prompt ' + (i + 1);
      lines.push((i + 1) + '. ' + firstLine.replace(/^#+\s*/, '').trim());
    });
  }
  lines.push('');
  lines.push('Interactive free layer: ' + siteOrigin + '/en/');
  return lines.join('\n') + '\n';
}


function buildSitemapXml(siteOrigin, root) {
  const urls = [
    { loc: siteOrigin + '/', file: 'index.html', images: [] },
    { loc: siteOrigin + '/en/', file: 'en/index.html', images: [
      siteOrigin + '/og.png',
      siteOrigin + '/assets/pdf-covers/cmo-starter-cover.png',
      siteOrigin + '/assets/pdf-covers/cmo-pro-cover.png',
      siteOrigin + '/assets/pdf-covers/cmo-bundle-cover.png'
    ]},
    { loc: siteOrigin + '/en/privacy.html', file: 'en/privacy.html', images: [] },
    { loc: siteOrigin + '/lt/', file: 'lt/index.html', images: [] },
    { loc: siteOrigin + '/lt/privatumas.html', file: 'lt/privatumas.html', images: [] },
    { loc: siteOrigin + '/terms.html', file: 'terms.html', images: [] }
  ];
  const parts = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">'
  ];
  for (const u of urls) {
    const lastmod = gitLastMod(u.file, root);
    parts.push('  <url>');
    parts.push('    <loc>' + u.loc + '</loc>');
    parts.push('    <lastmod>' + lastmod + '</lastmod>');
    for (const img of u.images) {
      parts.push('    <image:image>');
      parts.push('      <image:loc>' + img + '</image:loc>');
      parts.push('    </image:image>');
    }
    parts.push('  </url>');
  }
  parts.push('</urlset>');
  return parts.join('\n') + '\n';
}

